  ('40000000-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid,
  ('30000000-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid,
  '20000000-0000-4000-8000-000000000001'::uuid,
  ((n - 1) / 5) + 1,
  ((n - 1) % 5) + 1,
  date '2026-09-01'
