// 문장 규칙: 줄표(—)를 쓰지 않는다. 아이가 읽는 말투가 아니고 생성형 티가 난다.
// 같은 어미를 잇달아 쓰지 않는다. "빨강이구나. 오늘 하루가 힘들었구나." 처럼 "~구나" 가 겹치면
// 끄덕임을 두 번 하는 말투가 되어 우스워진다. 색은 쉼표로 받고 둘째 말은 "~싶네" "~인가 봐" 로 바꾼다.
// 흥정하는 말("하나만", "한 가지만")도 쓰지 않는다. 묻고 싶으면 그냥 묻는다.
