/**
 * 요일로 변주를 준다. 같은 날 다시 들어와도 같은 문장이 나오도록 날짜 기준으로 고른다
 * (무작위로 하면 새로고침할 때마다 바뀌어 아이가 혼란스럽다).
 */
export function pickOpener(flow: Flow, color: SignalColor, at: Date = new Date()): string {
  const pool = (flow === "checkin" ? CHECKIN : CHECKOUT)[color];
  return pool[at.getDay() % pool.length];
}

export const OPENERS = { checkin: CHECKIN, checkout: CHECKOUT };
