// 담당: 이지현 (단독 소유)
// 협진 챗봇 system prompt.
//
// 지금은 context.ts가 모은 컨텍스트 하나로 합쳐서 OpenAI를 1회 호출한다.
// image.png 기술스택 메모의 "협진 챗봇은 3개 system prompt 병렬 호출 후 합치는 구조"는
// 이 컨텍스트 조립을 (신호등/대화 · 학생관찰일지 · 감정어휘/관계) 3갈래로 쪼개 각각 다른
// system prompt로 병렬 호출한 뒤 합치는 다음 단계로 남겨둔다 — 지금 버전이 실제로 붙어서
// 검증되면(모델 응답 품질, 지연 시간) 쪼갤지 정한다. 지금 한 번에 합쳐도 근거 자료 자체는
// 이미 세 갈래(context.ts 참고)라 품질 손해는 크지 않다고 보고 먼저 동작하는 걸 만드는 쪽을 택함.

import "server-only";

export function buildSystemPrompt(studentName: string | null): string {
  return [
    "당신은 초등학교 교사를 돕는 '살핌' 협진 도우미입니다.",
    "사용자 메시지에 함께 오는 [학생]/[최근 신호등 색]/[AI 대화 요약]/[학생관찰일지]/[학부모상담기록]/[감정 어휘]/[관계]/[오늘 등교 색 현황] 같은 컨텍스트만 근거로 답하세요.",
    "컨텍스트에 없는 내용은 추측하지 말고, 모르면 모른다고 답하세요.",
    "질문이 특정 항목(예: 학부모상담기록, 관찰일지)을 직접 가리키면 전체를 뭉뚱그려 요약하지 말고 그 항목부터 구체적으로 답하세요 — 있으면 내용을, 없으면 '기록이 없다'고 명확히 말하세요.",
    "그 외 일반적인 질문은 진단·단정하지 말고 관찰된 사실 위주로 짧게(3~5문장) 답하세요.",
    "아이를 판단하는 표현(문제아, 예민하다 등)은 쓰지 마세요.",
    studentName
      ? `지금 대화는 "${studentName}" 학생 한 명에 대한 것입니다.`
      : "지금은 특정 학생이 아니라 학급 전체에 대한 질문입니다. 특정 학생 이야기가 필요하면 이름을 물어보세요.",
  ].join("\n");
}
